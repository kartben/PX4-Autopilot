#!/usr/bin/env python3
"""
Take the lines of a ranked ITCM list, from Tools/itcm_profile.py, in order while they fit in the
given number of bytes, and write them as a linker script fragment. A line that doesn't fit is
skipped, and a smaller one further down may still fit. A line without a size is always taken.

    itcm_fit.py <ranked list> <bytes> <output>
"""

import re
import sys


def main():
    ranked, budget, output = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    text = re.sub(r'/\*(?!\s*\d+\s*\*/).*?\*/', '', open(ranked).read(), flags=re.S)
    taken = []
    used = 0
    skipped = 0

    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue

        sized = re.match(r'(.*\S)\s*/\*\s*(\d+)\s*\*/$', line)
        if not sized:
            taken.append(line)
            continue

        # input sections are aligned on up to 8 bytes
        size = (int(sized.group(2)) + 7) & ~7
        if used + size > budget:
            skipped += 1
            continue

        used += size
        taken.append(sized.group(1))

    with open(output, 'w') as out:
        out.write(f'/* generated by itcm_fit.py from {ranked}: {used} of {budget} bytes */\n\n')
        out.write('\n'.join(taken) + '\n')

    print(f'{len(taken)} input sections, {used} of {budget} bytes, {skipped} left in the flash')


if __name__ == '__main__':
    main()
